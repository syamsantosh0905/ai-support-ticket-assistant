

import re
import streamlit as st

from database import create_table, save_ticket, get_tickets
from troubleshooting import get_troubleshooting_steps
from classifier import predict_ticket


st.set_page_config(
    page_title="AI Support Ticket Assistant",
    layout="wide"
)

create_table()

st.title("AI Support Ticket Classifier and Troubleshooting Assistant")

st.write(
    "Classify technical support tickets and review their predicted category and priority."
)

ticket_text = st.text_area(
    "Paste the customer support ticket text here:",
    height=200,
    placeholder="Example: After rotating the API token, our integration is failing with 401 unauthorized..."
)

if st.button("Analyze Ticket"):
    if not ticket_text.strip():
        st.warning("Please enter a support issue first.")

    else:
        try:
            with st.spinner("Analyzing ticket..."):
                category, priority = predict_ticket(ticket_text)

                ticket_id = save_ticket(
                    ticket_text,
                    category,
                    priority
                )

                steps = get_troubleshooting_steps(
                    category,
                    ticket_text
                )

            st.success(
                f"Ticket submitted successfully! Ticket ID: {ticket_id}"
            )

            st.subheader("Suggested Troubleshooting Steps")

            for step in steps:
                cleaned_step = step.strip()

                # Remove numbering generated by Gemini, if present.
                cleaned_step = re.sub(
                    r"^\s*\d+[\.\)\-]\s*",
                    "",
                    cleaned_step
                )

                if cleaned_step:
                    st.write(cleaned_step)

            col1, col2 = st.columns(2)

            with col1:
                st.metric("Predicted Category", category)

            with col2:
                st.metric("Predicted Priority", priority)

        except (ValueError, FileNotFoundError) as error:
            st.error(f"Could not analyze ticket: {error}")

st.divider()

st.subheader("Ticket History")

tickets = get_tickets()

if tickets:
    for ticket in reversed(tickets):
        ticket_id, description, category, priority, status = ticket

        with st.expander(f"Ticket #{ticket_id}"):
            st.write("Description:", description)
            st.write("Category:", category or "Not classified")
            st.write("Priority:", priority or "Not assigned")
            st.write("Status:", status)

else:
    st.info("No tickets submitted yet.")
